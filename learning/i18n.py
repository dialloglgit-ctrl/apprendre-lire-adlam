def normalize_lang(raw_lang):
    if not raw_lang:
        return "fr"
    candidate = str(raw_lang).strip().lower()

    # Alias courants pour Pulaar en script Adlam
    if candidate in {"pul", "pul-adlm", "ff-adlm"}:
        return "pul"

    # Alias pour Adlam script pur
    if candidate in {"adlm", "adlam"}:
        return "adlm"

    # Alias pour Arabe
    if candidate in {"ar", "ara", "ar-sa", "ar-dz"}:
        return "ar"

    code = candidate.split("-")[0]
    if code in SUPPORTED_LANGS:
        return code
    return "fr"


def get_text(lang, key):
    safe_lang = normalize_lang(lang)
    lang_pack = UI_TEXTS.get(safe_lang, UI_TEXTS["fr"])
    if key in lang_pack:
        return lang_pack[key]
    return UI_TEXTS["fr"].get(key, key)


